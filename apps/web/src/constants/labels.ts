export type LabelKey = keyof typeof LABELS;

export function label(key: LabelKey): string {
  return LABELS[key];
}

export function labeledStats(
  entries: ReadonlyArray<readonly [LabelKey, string | number, LabelKey?]>,
): Array<[string, string | number, string?]> {
  return entries.map(([key, value, hintKey]) => [
    LABELS[key],
    value,
    hintKey ? LABELS[hintKey] : undefined,
  ]);
}

export function destinationLabel(destination: 'dispatch' | 'warehouse'): string {
  return destination === 'warehouse' ? LABELS.warehouse : LABELS.dispatch;
}

export function statusLabel(status: string): string {
  if (status === 'PAID') return LABELS.statusPaid;
  if (status === 'VOID') return LABELS.statusVoid;
  if (status === 'CREDIT') return LABELS.statusCredit;
  return status;
}

export function expiryStatusLabel(status: string): string {
  if (status === 'expired') return LABELS.expiredStatus;
  if (status === 'today') return LABELS.expiresToday;
  return LABELS.expiringStatus;
}
